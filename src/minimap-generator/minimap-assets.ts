// Text assets for each minimap volume, in the exact formats the game's own `cs_minimap_create`
// writes (see the working de_dust2/de_inferno setup):
//   content: panorama/images/overheadmaps/<level>_<minimap>_radar.tga (+ .txt texture settings)
//   content: panorama/dynamic_image_<level>_<minimap>.vpdi
//   game:    resource/overviews/<level>.txt  "Volumes" block, one entry per minimap_name

import type { MinimapVolume } from "./config.ts";

export const radarBaseName = (levelName: string, minimapName: string) => `${levelName}_${minimapName}_radar`;

export const dynamicImageName = (levelName: string, minimapName: string) => `dynamic_image_${levelName}_${minimapName}.vpdi`;

// Written by the game with LF line endings.
